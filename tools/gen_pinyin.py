#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成拼音输入法字表头文件 pinyin_data.h

读取 gb2312_l1.txt（UTF-8，GB2312 一级字 3755 个，按拼音排序），
下载 pinyin-data 的 pinyin.txt 获取每个字的拼音，
下载 hanziDB（Jun Da 现代汉语字频表）对每个拼音音节内的候选字按使用频率排序，
输出 Core/Inc/pinyin_data.h：拼音音节 -> 候选汉字（UTF-8 用 \\x 转义，适配 armcc 的 GBK 源码读取）。

用法: python gen_pinyin.py
"""
import os
import csv
import io
import urllib.request

PROJECT = r"D:\STMPRO\ai_project"
CHAR_LIST = os.path.join(PROJECT, "tools", "font", "gb2312_l1.txt")
PINYIN_URL = "https://raw.githubusercontent.com/mozillazg/pinyin-data/master/pinyin.txt"
PINYIN_CACHE = os.path.join(PROJECT, "tools", "pinyin.txt")
HANZI_URL = "https://raw.githubusercontent.com/ruddfawcett/hanziDB.csv/master/hanzi_db.csv"
HANZI_CACHE = os.path.join(PROJECT, "tools", "hanzi_db.csv")
OUT = os.path.join(PROJECT, "Core", "Inc", "pinyin_data.h")
MAX_CHARS = 3755  # 全量一级字

# 声调字符 -> 无声调 ASCII（ü 记为 v，符合拼音输入法习惯）
TONE_TABLE = {
    0x0101: 'a', 0x00E1: 'a', 0x01CE: 'a', 0x00E0: 'a',   # ā á ǎ à
    0x0113: 'e', 0x00E9: 'e', 0x011B: 'e', 0x00E8: 'e',   # ē é ě è
    0x012B: 'i', 0x00ED: 'i', 0x01D0: 'i', 0x00EC: 'i',   # ī í ǐ ì
    0x014D: 'o', 0x00F3: 'o', 0x01D2: 'o', 0x00F2: 'o',   # ō ó ǒ ò
    0x016B: 'u', 0x00FA: 'u', 0x01D4: 'u', 0x00F9: 'u',   # ū ú ǔ ù
    0x01D6: 'v', 0x01D8: 'v', 0x01DA: 'v', 0x01DC: 'v',   # ǖ ǘ ǚ ǜ
    0x00FC: 'v',                                          # ü
    0x0144: 'n', 0x01F9: 'n', 0x0148: 'n',                # ń ǹ ň（嗯）
    0x1E3F: 'm',                                          # ḿ（呣）
}


def to_ascii(py):
    out = []
    for ch in py:
        o = ord(ch)
        if o in TONE_TABLE:
            out.append(TONE_TABLE[o])
        elif 'a' <= ch <= 'z':
            out.append(ch)
        # 其它字符（空格、标点、遗留声调）丢弃
    return "".join(out)


def fetch(url, cache):
    if os.path.exists(cache):
        with open(cache, "r", encoding="utf-8") as f:
            return f.read()
    print("downloading %s ..." % url)
    data = urllib.request.urlopen(url, timeout=60).read().decode("utf-8")
    os.makedirs(os.path.dirname(cache), exist_ok=True)
    with open(cache, "w", encoding="utf-8") as f:
        f.write(data)
    return data


def load_pinyin():
    data = fetch(PINYIN_URL, PINYIN_CACHE)
    mapping = {}
    for line in data.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        # 形如 "U+4E2D: zhōng, zhòng  # 中"
        head = line.split("#", 1)[0].strip()
        if ":" not in head:
            continue
        code_part, py_part = head.split(":", 1)
        code_part = code_part.strip()
        if not code_part.upper().startswith("U+"):
            continue
        try:
            cp = int(code_part[2:], 16)
        except ValueError:
            continue
        pinyins = []
        for seg in py_part.split(","):
            s = to_ascii(seg)
            if s and s not in pinyins:
                pinyins.append(s)
        if pinyins:
            mapping[cp] = pinyins
    print("parsed %d pinyin entries" % len(mapping))
    return mapping


def load_freq():
    """返回 {char: 频率名次}，名次越小越常用（Jun Da 现代汉语字频表）"""
    data = fetch(HANZI_URL, HANZI_CACHE)
    freq = {}
    reader = csv.reader(io.StringIO(data))
    next(reader, None)  # 跳过表头
    for rank, row in enumerate(reader, start=1):
        if row and len(row) > 1:
            ch = row[1].strip()
            if len(ch) == 1 and ch not in freq:
                freq[ch] = rank
    print("parsed %d frequency entries" % len(freq))
    return freq


def main():
    pinyin = load_pinyin()
    freq = load_freq()
    BIG = 10 ** 9

    with open(CHAR_LIST, "r", encoding="utf-8") as f:
        chars = f.read().strip()
    if len(chars) < MAX_CHARS:
        print("WARNING: char list only has %d chars" % len(chars))
    chars = chars[:MAX_CHARS]

    groups = {}  # py -> list of chars（保持出现顺序）
    missing = []
    for ch in chars:
        pys = pinyin.get(ord(ch))
        if not pys:
            missing.append(ch)
            continue
        for py in pys:
            groups.setdefault(py, []).append(ch)

    if missing:
        print("WARNING: %d chars missing pinyin: %s" % (len(missing), "".join(missing)))

    # 每个拼音音节内按使用频率排序（最常用在前，缺频次的排最后保持原序）
    for py in groups:
        groups[py] = sorted(groups[py], key=lambda c: freq.get(c, BIG))

    lines = []
    total_utf8 = 0
    for py in sorted(groups):
        chs = "".join(groups[py])
        esc = "".join("\\x%02X" % b for b in chs.encode("utf-8"))
        total_utf8 += len(chs.encode("utf-8"))
        lines.append('    {"%s", "%s"},' % (py, esc))

    body = "\n".join(lines)
    header = (
        "/* Pinyin IME data - auto-generated by tools/gen_pinyin.py, do not edit.\n"
        " * %d GB2312 level-1 chars, %d pinyin syllables (candidates sorted by usage frequency).\n"
        " */\n"
        "#ifndef PY_IME_DATA_H\n"
        "#define PY_IME_DATA_H\n"
        "\n"
        "typedef struct {\n"
        "    const char *py;\n"
        "    const char *chs;\n"
        "} py_group_t;\n"
        "\n"
        "static const py_group_t py_groups[] = {\n"
        "%s\n"
        "};\n"
        "\n"
        "#define PY_GROUP_COUNT (sizeof(py_groups) / sizeof(py_groups[0]))\n"
        "\n"
        "#endif /* PY_IME_DATA_H */\n"
    ) % (MAX_CHARS, len(groups), body)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii") as f:
        f.write(header)
    print("wrote %s: %d groups, %d chars, %d bytes utf8" %
          (OUT, len(groups), len(chars), total_utf8))


if __name__ == "__main__":
    main()
